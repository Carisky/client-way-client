const initialLanguage = (localStorage.getItem(STORAGE_KEY) as AppLanguage | null) ?? "en";
const language = ref<AppLanguage>(initialLanguage in translations ? initialLanguage : "en");

export function useI18n() {
  const setLanguage = (value: AppLanguage) => {
    language.value = value;
    localStorage.setItem(STORAGE_KEY, value);
    document.documentElement.lang = value;
  };

  const t = (key: string, params?: Record<string, string | number | null | undefined>) => {
    const template = translations[language.value][key] ?? key;

    if (!params) {
      return template;
    }

    return Object.entries(params).reduce((value, [param, replacement]) => {
      return value.split(`{${param}}`).join(String(replacement ?? ""));
    }, template);
  };

  return {
    language,
    languageLabel: computed(() => languageOptions.find((option) => option.value === language.value)?.label ?? "English"),
    languageOptions,
    setLanguage,
    t,
  };
}

document.documentElement.lang = language.value;
